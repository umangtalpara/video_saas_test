#!/usr/bin/env node
/**
 * sync-adapters.js — generates the tool-specific folders from the canonical `.ai/` sources.
 *
 *   node .ai/scripts/sync-adapters.js            # (re)generate everything
 *   node .ai/scripts/sync-adapters.js --check    # verify adapters are up to date (exit 1 if not) — use in CI
 *   node .ai/scripts/sync-adapters.js --force    # one-time migration: overwrite pre-existing hand-written files at generated paths
 *
 * Sources (each has `name` + `description` frontmatter):
 *   .ai/agents/*.md     -> .claude/agents (Claude Code + Cursor), .agents/agents (Antigravity)
 *   .ai/skills/*.md     -> .claude/skills/<name>/SKILL.md, .agents/skills/<name>/SKILL.md (Cursor reads both)
 *   .ai/workflows/*.md  -> skills named `factory-<name>` (slash commands everywhere) + .cursor/commands/factory-<name>.md
 *   .ai/context/*.md    -> .cursor/rules/*.mdc (scoped), .agents/rules/*.md (Antigravity, with `trigger`)
 *
 * Why: Claude Code needs `name`/`description` frontmatter on sub-agents, Antigravity silently drops rules without a
 * valid `trigger`, and skills are the one format all three tools share (and expose as slash commands).
 * Generated files carry a marker comment; only marker-bearing files are ever deleted as stale.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '../..');
const AI = path.join(ROOT, '.ai');
const CHECK = process.argv.includes('--check');
const FORCE = process.argv.includes('--force');
const MARKER = '<!-- generated by .ai/scripts/sync-adapters.js — do not edit; edit the source in .ai/ and re-run -->';

const colors = { reset: '\x1b[0m', green: '\x1b[32m', yellow: '\x1b[33m', red: '\x1b[31m', blue: '\x1b[34m', bold: '\x1b[1m' };
const log = (m, c = colors.reset) => console.log(`${c}${m}${colors.reset}`);

// ---------- read sources ----------
function parseFrontmatter(src, file) {
  const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!m) throw new Error(`${path.relative(ROOT, file)}: missing frontmatter (name, description)`);
  const data = {};
  m[1].split(/\r?\n/).forEach((line) => {
    const kv = line.match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (!kv) return;
    let v = kv[2].trim();
    if (v.startsWith('"') && v.endsWith('"')) v = JSON.parse(v);
    data[kv[1]] = v;
  });
  return data;
}

function readDir(sub) {
  const dir = path.join(AI, sub);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort().map((f) => {
    const file = path.join(dir, f);
    const fm = parseFrontmatter(fs.readFileSync(file, 'utf8'), file);
    const base = f.replace(/\.md$/, '');
    if (!fm.name || !fm.description) throw new Error(`${sub}/${f}: frontmatter needs name and description`);
    if (fm.name !== base) throw new Error(`${sub}/${f}: frontmatter name "${fm.name}" must equal the file name "${base}"`);
    return { ...fm, base, rel: `.ai/${sub}/${f}` };
  });
}

const agents = readDir('agents');
const skills = readDir('skills');
const workflows = readDir('workflows');
const contexts = readDir('context');

// ---------- builders ----------
const q = (s) => JSON.stringify(String(s)); // YAML-safe double-quoted string
const fm = (obj) => `---\n${Object.entries(obj).filter(([, v]) => v !== undefined).map(([k, v]) => `${k}: ${v}`).join('\n')}\n---\n${MARKER}\n\n`;
const title = (s) => s.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');

const out = new Map(); // relative path (posix) -> content
const add = (rel, content) => out.set(rel, content.replace(/\r\n/g, '\n'));

const skillBody = (src) => `Read \`${src}\` in full and follow it. Paths are relative to the repository root. Shared rules: \`AGENTS.md\`.\n`;
const workflowBody = (wf) => `Act as the **Super Agent** (\`.ai/agents/super-agent.md\`). Read \`${wf.rel}\` in full and execute it step by step. Paths are relative to the repository root.\n\n- Follow \`AGENTS.md\`.\n- Record state only through \`node .ai/scripts/status-manager.js\` (run \`help\` for commands).\n- Never redo COMPLETED tasks; stop and ask the user when a blocker is logged.\n`;
const agentBody = (a) => `You are the **${title(a.name)}** of the SaaS AI Factory.\n\nBefore doing anything, read \`${a.rel}\` in full and follow it exactly, together with the shared rules in \`AGENTS.md\`. Load the context files and skills it lists (see \`.ai/context/\` and \`.ai/skills/\`). Paths are relative to the repository root.\n\nWork only on the task you were assigned, update progress through \`node .ai/scripts/status-manager.js\`, and finish with the \`task_result\` / report format defined in your persona file.\n`;

// Sub-agents. The Super Agent is intentionally NOT a Claude/Cursor sub-agent: sub-agents cannot spawn sub-agents,
// so the main chat session plays the Super Agent (AGENTS.md "Entry Point"). Antigravity gets it as a selectable main agent.
agents.forEach((a) => {
  if (a.mode !== 'main') {
    add(`.claude/agents/${a.base}.md`, fm({ name: a.name, description: q(a.description), model: 'inherit' }) + agentBody(a));
  }
  add(`.agents/agents/${a.base}.md`, fm({
    name: a.name, description: q(a.description), model: 'inherit',
    mainAgent: a.mode === 'main', subagent: a.mode !== 'main'
  }) + agentBody(a));
});

// Skills (knowledge) and workflow skills (slash commands)
skills.forEach((s) => {
  const body = fm({ name: s.name, description: q(s.description) }) + skillBody(s.rel);
  add(`.claude/skills/${s.base}/SKILL.md`, body);
  add(`.agents/skills/${s.base}/SKILL.md`, body);
});
workflows.forEach((w) => {
  const name = `factory-${w.base}`;
  const body = fm({ name, description: q(w.description) }) + workflowBody(w);
  add(`.claude/skills/${name}/SKILL.md`, body);
  add(`.agents/skills/${name}/SKILL.md`, body);
  add(`.cursor/commands/${name}.md`, `${MARKER}\n\n# ${title(w.base)}\n\n${w.description}\n\n${workflowBody(w)}`);
});

// Rules. Cursor: scoped (.mdc). Antigravity: needs `trigger` or the file is silently discarded.
contexts.forEach((c) => {
  add(`.cursor/rules/${c.base}.mdc`, fm({
    description: q(c.description), globs: c.globs ? c.globs : undefined, alwaysApply: false
  }) + `Follow the conventions in @${c.rel}.\n`);
  const trigger = c.globs ? { trigger: 'glob', description: q(c.description), globs: q(c.globs) } : { trigger: 'model_decision', description: q(c.description) };
  add(`.agents/rules/${c.base}.md`, fm(trigger) + `@[${title(c.base)}](../../${c.rel})\n`);
});

// ---------- write / check ----------
const MANAGED = [
  ['.claude/agents', /\.md$/], ['.agents/agents', /\.md$/], ['.agents/rules', /\.md$/], ['.cursor/rules', /\.mdc$/], ['.cursor/commands', /\.md$/]
];
const SKILL_ROOTS = ['.claude/skills', '.agents/skills'];

function listManaged() {
  const files = [];
  MANAGED.forEach(([dir, re]) => {
    const abs = path.join(ROOT, dir);
    if (fs.existsSync(abs)) fs.readdirSync(abs).filter((f) => re.test(f)).forEach((f) => files.push(`${dir}/${f}`));
  });
  SKILL_ROOTS.forEach((dir) => {
    const abs = path.join(ROOT, dir);
    if (!fs.existsSync(abs)) return;
    fs.readdirSync(abs, { withFileTypes: true }).filter((d) => d.isDirectory()).forEach((d) => {
      if (fs.existsSync(path.join(abs, d.name, 'SKILL.md'))) files.push(`${dir}/${d.name}/SKILL.md`);
    });
  });
  return files;
}

const problems = [];
let written = 0;
for (const [rel, content] of out) {
  const abs = path.join(ROOT, rel);
  const existing = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n') : null;
  if (existing === content) continue;
  if (existing !== null && !existing.includes(MARKER) && !FORCE) {
    problems.push(`${rel}: exists but is not generated (no marker) — move or delete it`);
    continue;
  }
  if (CHECK) { problems.push(`${rel}: ${existing === null ? 'missing' : 'out of date'}`); continue; }
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
  written++;
}

let removed = 0;
listManaged().filter((rel) => !out.has(rel)).forEach((rel) => {
  const abs = path.join(ROOT, rel);
  if (!fs.readFileSync(abs, 'utf8').includes(MARKER)) return; // user-owned file, leave alone
  if (CHECK) { problems.push(`${rel}: stale generated file (source removed)`); return; }
  fs.unlinkSync(abs);
  if (rel.endsWith('/SKILL.md')) { try { fs.rmdirSync(path.dirname(abs)); } catch (e) { /* not empty */ } }
  removed++;
});

if (CHECK) {
  if (problems.length) { log(`✘ Adapters are out of sync (${problems.length}):`, colors.red); problems.forEach((p) => console.log('  - ' + p)); log('Run: node .ai/scripts/sync-adapters.js', colors.yellow); process.exit(1); }
  log(`✔ All ${out.size} adapter files are up to date.`, colors.green);
  process.exit(0);
}
problems.forEach((p) => log(`⚠ ${p}`, colors.yellow));
log(`✔ Adapters synced: ${out.size} files managed (${written} written, ${removed} stale removed) — ${agents.length} agents, ${skills.length} skills, ${workflows.length} workflows, ${contexts.length} rules.`, colors.green);
process.exit(problems.length ? 1 : 0);
